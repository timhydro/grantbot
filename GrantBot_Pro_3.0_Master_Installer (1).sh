    [[ -f "$APP_DIR/grantbot.db" ]] && cp -a "$APP_DIR/grantbot.db" "$BACKUP/grantbot.db"
    [[ -f "$APP_DIR/.env" ]] && cp -a "$APP_DIR/.env" "$BACKUP/.env"
  fi

  if [[ "$FORCE" -ne 1 ]]; then
    if [[ -t 0 ]]; then
      printf '\nExisting installation found at: %s\n' "$APP_DIR"
      read -r -p "Replace it? [y/N] " ans
      [[ "$ans" =~ ^[Yy]$ ]] || die "Installation cancelled"
    else
      die "Target exists. Re-run with --force, or choose --dir PATH"
    fi
  fi
  rm -rf "$APP_DIR"
fi

mkdir -p "$(dirname "$APP_DIR")"
cp -a "$SRC" "$APP_DIR"
chmod +x "$APP_DIR/bootstrap.sh"

if [[ "$PRESERVE" -eq 1 ]]; then
  [[ -f "$BACKUP/grantbot.db" ]] && cp -a "$BACKUP/grantbot.db" "$APP_DIR/grantbot.db"
  [[ -f "$BACKUP/.env" ]] && cp -a "$BACKUP/.env" "$APP_DIR/.env"
fi

log "Full GrantBot Pro source installed at $APP_DIR"
printf 'Files: %s\n' "$(find "$APP_DIR" -type f | wc -l | tr -d ' ')"
printf 'Python modules: %s\n' "$(find "$APP_DIR/grantbot" -name '*.py' -type f | wc -l | tr -d ' ')"

if [[ "$DO_INSTALL" -eq 1 ]]; then
  # Chromebook/Debian convenience: venv is sometimes not installed with Python.
  if ! python3 -m venv "$TMP_ROOT/venv-check" >/dev/null 2>&1; then
    rm -rf "$TMP_ROOT/venv-check"
    if command -v apt-get >/dev/null 2>&1 && command -v sudo >/dev/null 2>&1; then
      log "python3-venv is missing; installing required system package"
      sudo apt-get update
      sudo apt-get install -y python3-venv python3-pip
    else
      die "Python venv support is missing. Install python3-venv and rerun."
    fi
  else
    rm -rf "$TMP_ROOT/venv-check"
  fi

  log "Running the release bootstrap, dependency install, compile check, database init, and pytest suite"
  (cd "$APP_DIR" && bash bootstrap.sh)

  log "Installation verification"
  (cd "$APP_DIR" && .venv/bin/python -m grantbot status)
fi

cat <<EOF

============================================================
 GRANTBOT PRO 3.0 COMPLETE IS READY
============================================================
Location: $APP_DIR

Start server:
  cd "$APP_DIR" && .venv/bin/python -m grantbot serve

Dashboard:
  http://127.0.0.1:5000

Useful commands:
  cd "$APP_DIR" && .venv/bin/python -m grantbot status
  cd "$APP_DIR" && .venv/bin/python -m grantbot questions
  cd "$APP_DIR" && .venv/bin/python -m grantbot missing --required
  cd "$APP_DIR" && .venv/bin/python -m grantbot write "Describe your employment and job training program"
  cd "$APP_DIR" && .venv/bin/python -m grantbot discover "reentry workforce" --rows 20
  cd "$APP_DIR" && .venv/bin/python -m grantbot nofo /path/to/NOFO.pdf
============================================================
EOF

if [[ "$DO_START" -eq 1 ]]; then
  [[ "$DO_INSTALL" -eq 1 ]] || die "--start requires installation; remove --no-install"
  log "Starting GrantBot Pro on http://${HOST}:${PORT}"
  args=(serve --host "$HOST" --port "$PORT")
  [[ "$DEBUG" -eq 1 ]] && args+=(--debug)
  cd "$APP_DIR"
  exec .venv/bin/python -m grantbot "${args[@]}"
fi
